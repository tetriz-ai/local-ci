// Package projectinfo defines ProjectInfo, the data object a run threads from
// prepper to checker to stamper (repo paths, PR data, the diff, and results).
package projectinfo

import (
	"fmt"
	"path/filepath"

	"github.com/google/go-github/v60/github"

	"github.com/tetriz-ai/local-ci/internal/projectroot"
	"github.com/tetriz-ai/local-ci/workflow"
)

// ProjectInfo is the common data object passed from the start to the end of the
// runner lifecycle. It carries info from prepper -> checker and checker -> stamper.
type ProjectInfo struct {
	UserInput *UserInput
	RepoPath  string
	// MainRepoRoot is the root of the main git worktree. Equals RepoPath when not in a
	// worktree. Use this for shared state (git notes, etc.) that legitimately spans
	// worktrees. Do NOT use it for output file paths — those go to OutputDir, which
	// is worktree-scoped.
	MainRepoRoot string

	// OutputDir is the directory where local-ci writes its run output (logs, JSON,
	// summary files). Equals filepath.Join(RepoPath, "output", "local-ci") — scoped to
	// the current git worktree so parallel local-ci runs from different worktrees
	// don't collide on the same output files.
	OutputDir string
	GitData   *GitData
	PrData    *PrData
	DiffData  *DiffData
	// CheckerStatus holds the map of checker name to execution status
	CheckerStatus map[string]bool
	ToolInfo      *ToolInfo
	// AffectedWorkflows contains the workflows affected by the diff (from the last
	// stamp if present, else the overall PR), after the user filter is applied.
	AffectedWorkflows []*workflow.Workflow
	// ExcludedAffectedWorkflows lists affected workflows excluded by the user's --enable filter.
	ExcludedAffectedWorkflows []string
	CommonImpactedPaths       []string
	LastValidStamp            StampInfo
	CurrDir                   string
	RepoName                  string
	// RepoOwner is the GitHub owner (org or user) parsed from the git remote,
	// used for GitHub API calls. Empty when the remote is unavailable.
	RepoOwner string
}

type StampInfo struct {
	CommitSHA    string          `json:"commitSha"`
	ChecksStatus map[string]bool `json:"checksStatus"`
	Version      string          `json:"version"`
	BaseBranch   string          `json:"baseBranch"`
}

// PrData stores PR-related info generated by githubDataPrepper.
type PrData struct {
	BaseBranch   string
	HeadBranch   string
	LatestCommit string
	AllCommits   []string
	PrFiles      []*github.CommitFile
}

// DiffData stores the enriched diff info and the last stamp info generated by diffPrepper.
type DiffData struct {
	// FilesChanges are optimised changes from the last valid stamp (if present).
	FilesChanges *AffectedFiles
	// OverallFilesChanges are the total changes from the first commit of the PR.
	OverallFilesChanges *AffectedFiles
	// OptimisedFileChangesPresent signifies that FilesChanges holds the optimised
	// (since-last-stamp) changes rather than the overall ones.
	OptimisedFileChangesPresent bool
}

// ToolInfo stores info related to local-ci itself.
type ToolInfo struct {
	Version string
}

// GitData stores output generated by gitDataPrepper.
type GitData struct{}

type AffectedFiles struct {
	ModifiedFiles []string
	RemovedFiles  []string
	// NonRemovedFiles is a subset of ModifiedFiles excluding RemovedFiles.
	NonRemovedFiles []string
	// NewFiles contains only the files that were added (not modified or renamed).
	NewFiles []string
}

// FilterFilesByExtension returns the non-removed changed files with the given
// extension (e.g. ".go"), as passed to filepath.Ext.
func (af *AffectedFiles) FilterFilesByExtension(ext string) []string {
	filteredFiles := make([]string, 0)
	for _, file := range af.NonRemovedFiles {
		if filepath.Ext(file) == ext {
			filteredFiles = append(filteredFiles, file)
		}
	}
	return filteredFiles
}

// UserInput holds the flags and info the user passes to local-ci.
type UserInput struct {
	PrNumber           int
	SelectiveWorkflows []string
	// DisabledWorkflows are checkers the user opted out of by name (the --disable
	// flag). They are never run and never stamped, so a host or adopter can turn off
	// a checker (e.g. a team-policy one) without forking the checker set. A gate that
	// requires a disabled check will fail, which is the honest outcome of opting out
	// of a required check.
	DisabledWorkflows []string
	ForceRunCheck     bool
	DryRunMode        bool
	GhActionMode      bool
}

func NewProjectInfo(userInput *UserInput, toolVersion string) (*ProjectInfo, error) {
	repoPath, err := projectroot.GetRepoRoot()
	if err != nil {
		return nil, fmt.Errorf("failed to get repo root: %w", err)
	}

	repoName, currDir := GetRepoName(repoPath)
	mainRepoRoot := projectroot.GetMainRepoRoot(repoPath)
	return &ProjectInfo{
		RepoPath:      repoPath,
		MainRepoRoot:  mainRepoRoot,
		OutputDir:     filepath.Join(repoPath, "output", "local-ci"),
		CheckerStatus: make(map[string]bool),
		UserInput:     userInput,
		ToolInfo:      &ToolInfo{Version: toolVersion},
		RepoName:      repoName,
		RepoOwner:     projectroot.GetRepoOwner(repoPath),
		CurrDir:       currDir,
	}, nil
}

// GetRepoName returns the repository name from the repo path (both return values
// are the same name; the pair is kept for callers that bind repoName and currDir
// separately). It delegates to projectroot.GetRepoName — the single, worktree-aware
// source of truth (git remote origin, basename fallback) shared with the deps tool.
func GetRepoName(repoPath string) (string, string) {
	name := projectroot.GetRepoName(repoPath)
	return name, name
}
